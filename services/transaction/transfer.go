// Package transaction is the transaction service: it takes requests to move
// money (a transfer between two accounts, or a deposit from outside the
// bank), records each one, and sees it through until the ledger has posted
// it or refused it for good.
//
// Every transfer is a small state machine. It starts pending, is saved before
// anything is sent to the ledger, and ends completed or failed. While it's
// pending it can be tried again any number of times, always with the same
// ledger idempotency key (the transfer's own ID), so retries can never move
// the money twice. Its Postgres schema lives in migrations/, applied by
// db.Migrate when the service starts (ADR-0005).
package transaction

import (
	"time"
	"uuid"

	"github.com/monzo/terrors"

	"github.com/tinypell3ts/tiny-bank/pkg/kit"
	"github.com/tinypell3ts/tiny-bank/pkg/money"
)

// Kind says where a transfer's money comes from.
type Kind string

const (
	// KindTransfer moves money from one account to another.
	KindTransfer Kind = "transfer"
	// KindDeposit moves money into an account from outside the bank (the
	// ledger's funding account for the currency), so it has no From.
	KindDeposit Kind = "deposit"
)

// State is where a transfer is in its life. Only pending ever changes:
// completed and failed are final.
type State string

const (
	// StatePending: saved, and not yet posted or refused by the ledger. It may
	// be tried any number of times.
	StatePending State = "pending"
	// StateCompleted: the ledger posted it. JournalID says which journal.
	StateCompleted State = "completed"
	// StateFailed: the ledger refused it for good (insufficient funds, an
	// account that isn't open). FailureReason says why.
	StateFailed State = "failed"
)

// Transfer is one request to move money, and what has happened to it.
type Transfer struct {
	ID uuid.UUID // generated by Postgres; also the ledger's idempotency key
	// IdempotencyKey is the caller's: a retry of the same request gets this
	// transfer back instead of a new one.
	IdempotencyKey string
	Kind           Kind
	From           uuid.UUID // uuid.Nil() for a deposit
	To             uuid.UUID
	Amount         money.Money
	State          State
	JournalID      uuid.UUID // set once completed
	FailureReason  string    // set once failed: the ledger's terror code, like precondition_failed.insufficient_funds
	Attempts       int       // how many times it's been sent to the ledger
	NextAttemptAt  time.Time // when a pending transfer is next due to be tried
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

// maxAmount bounds one transfer, as the ledger bounds one entry: 10^12 minor
// units, £10 billion. The ledger would refuse more anyway; checking here
// refuses it before anything is saved.
const maxAmount = 1_000_000_000_000

// NewTransfer is a request to move money.
type NewTransfer struct {
	IdempotencyKey string
	Kind           Kind
	From           uuid.UUID // leave as uuid.Nil() for a deposit
	To             uuid.UUID
	Amount         money.Money
}

func invalid(field, message string) error { return terrors.BadRequest(field, message, nil) }

// Validate checks the rules that don't need the ledger: a good key, a known
// kind, accounts that make sense for it, and an amount from 1 minor unit to
// maxAmount. Whether the money is there and the accounts are open is the
// ledger's to decide.
func (t NewTransfer) Validate() error {
	if err := kit.CheckIdempotencyKey(t.IdempotencyKey); err != nil {
		return err
	}
	switch t.Kind {
	case KindTransfer:
		if t.From == uuid.Nil() {
			return invalid("from", "a transfer needs an account to take the money from")
		}
	case KindDeposit:
		if t.From != uuid.Nil() {
			return invalid("from", "a deposit comes from outside the bank, so it has no from account")
		}
	default:
		return invalid("kind", "kind must be transfer or deposit")
	}
	if t.To == uuid.Nil() {
		return invalid("to", "an account to put the money in is required")
	}
	if t.From == t.To {
		return invalid("to", "a transfer can't be to the account it's from")
	}
	if t.Amount.Currency() == (money.Currency{}) {
		return invalid("currency", "currency is required")
	}
	if a := t.Amount.Amount(); a < 1 || a > maxAmount {
		return invalid("amount", "amount must be from 1 to 1000000000000 minor units")
	}
	return nil
}

// same reports whether t asks for the same movement of money as an existing
// transfer. A request with an existing key must, or the key was reused for
// something else.
func (t NewTransfer) same(existing Transfer) bool {
	return t.Kind == existing.Kind && t.From == existing.From && t.To == existing.To && t.Amount == existing.Amount
}

// errNotFound and errKeyReused are expected answers, built without a stack
// trace, like the ledger's.
func errNotFound() error {
	return &terrors.Error{Code: terrors.ErrNotFound + ".transfer", Message: "transfer not found", Params: map[string]string{}}
}

// errKeyReused is a request whose key was already used for a different
// transfer: almost always a caller bug, so it's refused, not treated as a retry.
func errKeyReused() error {
	return terrors.PreconditionFailed("idempotency_key", "this idempotency key was already used for a different transfer", nil)
}
