// Package ledger is the ledger service: the one record of every movement of
// money, kept by double-entry bookkeeping. Its Postgres schema lives in
// migrations/, applied by db.Migrate when the service starts (ADR-0005).
//
// Money only ever moves in journals. A journal is a set of entries, each
// adding to or taking from one account, and its entries always add up to
// zero: money is never created or destroyed, only moved. Money arriving from
// outside the bank comes from a funding account, which may go negative.
// Customer accounts never go below zero.
package ledger

import (
	"fmt"
	"regexp"
	"slices"
	"time"
	"uuid"

	"github.com/monzo/terrors"

	"github.com/tinypell3ts/tiny-bank/pkg/money"
)

// Entry moves Amount into one account: a positive amount adds to its
// balance, a negative one takes from it.
type Entry struct {
	AccountID uuid.UUID
	Amount    money.Money
}

// Journal is a posted set of entries, which add up to zero.
type Journal struct {
	ID             uuid.UUID // generated by Postgres
	IdempotencyKey string
	Currency       money.Currency
	Entries        []Entry // sorted by account ID
	CreatedAt      time.Time
}

// Balance is how much money an account holds, by the ledger's record.
type Balance struct {
	AccountID uuid.UUID
	Kind      Kind
	Amount    money.Money
}

// Kind says which rules an account follows.
type Kind string

const (
	// KindCustomer is a customer's account. Its balance never goes below zero.
	KindCustomer Kind = "customer"
	// KindFunding is where money arriving from outside the bank comes from.
	// Its balance goes negative as money comes in: -£100 means £100 has
	// arrived and been moved into customer accounts.
	KindFunding Kind = "funding"
)

// FundingAccount returns the ID of the funding account for c. The ledger's
// migrations create one for each supported currency. Each ID ends in the
// currency's ISO 4217 number (826 for GBP), so it's easy to spot in logs.
func FundingAccount(c money.Currency) (uuid.UUID, bool) {
	id, ok := fundingAccounts[c.Code()]
	return id, ok
}

var fundingAccounts = map[string]uuid.UUID{
	"GBP": uuid.MustParse("00000000-0000-4000-8000-000000000826"),
	"EUR": uuid.MustParse("00000000-0000-4000-8000-000000000978"),
	"USD": uuid.MustParse("00000000-0000-4000-8000-000000000840"),
	"JPY": uuid.MustParse("00000000-0000-4000-8000-000000000392"),
}

const (
	// maxEntries bounds how many accounts one journal locks. A transfer needs
	// two; a few more covers fees.
	maxEntries = 10
	// maxKeyLen bounds the idempotency key. A UUID is 36 characters.
	maxKeyLen = 100
	// maxAmount bounds one entry: 10^12 minor units, £10 billion. Without a
	// bound, a few huge journals could take a balance near the int64 limit,
	// after which every post to that account would overflow. With it, a
	// balance needs millions of maximum-size journals to get there.
	maxAmount = 1_000_000_000_000
)

// keyPattern is what an idempotency key may contain: letters, digits and a
// few separators, so a key is safe to log.
var keyPattern = regexp.MustCompile(`^[A-Za-z0-9._:-]+$`)

// NewJournal is a request to move money.
type NewJournal struct {
	// IdempotencyKey is chosen by the caller, once per movement of money. A
	// request sent again with the same key, after a timeout for example,
	// returns the journal already posted instead of moving the money twice.
	IdempotencyKey string
	Entries        []Entry
}

func invalid(field, message string) error { return terrors.BadRequest(field, message, nil) }

// Validate checks j and returns it with its entries sorted by account ID.
// Sorting gives one journal one form, whatever order its entries arrived in,
// so a retry compares equal to the journal it repeats, and an account listed
// twice is next to itself.
func (j NewJournal) Validate() (NewJournal, error) {
	switch n := len(j.IdempotencyKey); {
	case n == 0:
		return NewJournal{}, invalid("idempotency_key", "idempotency key is required")
	case n > maxKeyLen:
		return NewJournal{}, invalid("idempotency_key", fmt.Sprintf("idempotency key must be at most %d characters", maxKeyLen))
	case !keyPattern.MatchString(j.IdempotencyKey):
		return NewJournal{}, invalid("idempotency_key", "idempotency key may only contain letters, digits and . _ : -")
	}
	switch n := len(j.Entries); {
	case n < 2:
		return NewJournal{}, invalid("entries", "a journal needs at least two entries")
	case n > maxEntries:
		return NewJournal{}, invalid("entries", fmt.Sprintf("a journal may have at most %d entries", maxEntries))
	}

	entries := slices.Clone(j.Entries) // never reorder the caller's slice
	slices.SortFunc(entries, func(a, b Entry) int { return a.AccountID.Compare(b.AccountID) })

	currency := entries[0].Amount.Currency()
	total := money.New(0, currency)
	for i, e := range entries {
		if e.AccountID == uuid.Nil() {
			return NewJournal{}, invalid("entries", "every entry needs an account ID")
		}
		if i > 0 && e.AccountID == entries[i-1].AccountID {
			return NewJournal{}, invalid("entries", "an account may appear only once in a journal")
		}
		if e.Amount.Currency() == (money.Currency{}) {
			return NewJournal{}, invalid("entries", "every entry needs a currency")
		}
		if e.Amount.Currency() != currency {
			return NewJournal{}, invalid("entries", "every entry in a journal must be in the same currency")
		}
		if a := e.Amount.Amount(); a == 0 {
			return NewJournal{}, invalid("entries", "an entry's amount must not be zero")
		} else if a > maxAmount || a < -maxAmount {
			return NewJournal{}, invalid("entries", fmt.Sprintf("an entry's amount must be at most %d minor units either way", maxAmount))
		}
		var err error
		if total, err = total.Add(e.Amount); err != nil {
			// Each amount is bounded above, so ten of them can't overflow.
			return NewJournal{}, fmt.Errorf("add entries: %w", err)
		}
	}
	if total.Amount() != 0 {
		return NewJournal{}, invalid("entries", "a journal's entries must add up to zero")
	}
	j.Entries = entries
	return j, nil
}

// errJournalNotFound and errAccountNotFound are expected answers, so like the
// account service's errNotFound they're built without a stack trace.
func errJournalNotFound() error {
	return &terrors.Error{Code: terrors.ErrNotFound + ".journal", Message: "journal not found", Params: map[string]string{}}
}

func errAccountNotFound() error {
	return &terrors.Error{Code: terrors.ErrNotFound + ".account", Message: "the ledger has no record of this account", Params: map[string]string{}}
}

// errKeyReused is a request whose key was already used for a different
// journal. That's almost always a bug in the caller, such as a key built from
// the wrong thing, so it's refused rather than treated as a retry.
func errKeyReused() error {
	return terrors.PreconditionFailed("idempotency_key", "this idempotency key was already used for a different journal", nil)
}

// errInsufficientFunds names the account (a random UUID, safe to share) but
// never its balance.
func errInsufficientFunds(id uuid.UUID) error {
	return terrors.PreconditionFailed("insufficient_funds", "account "+id.String()+" doesn't hold enough money", nil)
}

func errWrongCurrency(id uuid.UUID, c money.Currency) error {
	return terrors.BadRequest("currency", "account "+id.String()+" holds "+c.Code(), nil)
}
